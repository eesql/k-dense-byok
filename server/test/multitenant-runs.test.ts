import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { createServer, type ServerResponse } from "node:http";
import { expect, it, vi } from "vitest";
import { TenantStore } from "../src/multitenant/store.ts";
import { WorkerFleet } from "../src/multitenant/workers.ts";
import { buildManagementApp } from "../src/multitenant/server.ts";
import { ModelGateway } from "../src/multitenant/model-gateway.ts";

it("routes actual Pi streams through the platform gateway and drains credential updates without changing an active run's key", async () => {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), "kady-managed-runs-"));
  const store = new TenantStore(root), admin = await store.initializeAdmin("administrator", "synthetic-admin-password");
  const tenant = store.createTenant(admin, { name: "Lab", budgetUsd: null });
  const invite = store.invite(admin, tenant.id, "owner"), user = await store.join({ token: invite.token, username: "researcher", password: "synthetic-admin-password" });
  const a = store.createProject(user, { name: "Busy BYOK" }).project;
  const idle = store.createProject(user, { name: "Idle BYOK" }).project;
  const p = store.createProject(user, { name: "Platform", supply: "platform" }).project;
  const calls: { auth: string; held: boolean; followup: boolean; child: boolean; model: string; maxTokens: number }[] = [];
  let held: ServerResponse | undefined;
  let heldChild: ServerResponse | undefined;
  let childTranscript = "";
  let scheduleTranscript = "";
  let controlState = "";
  let delegatedSession = "";
  const chunk = (response: ServerResponse, data: unknown) => response.write(`data: ${JSON.stringify(data)}\n\n`);
  const finish = (response: ServerResponse, tool: boolean | { name: string; args: unknown } = false) => {
    if (tool) chunk(response, { id: "scan", object: "chat.completion.chunk", choices: [{ index: 0, delta: { tool_calls: [{ index: 0, id: "scan", type: "function", function: { name: typeof tool === "object" ? tool.name : "ls", arguments: JSON.stringify(typeof tool === "object" ? tool.args : { path: "." }) } }] }, finish_reason: null }] });
    else chunk(response, { id: "answer", object: "chat.completion.chunk", choices: [{ index: 0, delta: { content: "Model answered." }, finish_reason: null }] });
    chunk(response, { id: "finished", object: "chat.completion.chunk", choices: [{ index: 0, delta: {}, finish_reason: tool ? "tool_calls" : "stop" }], usage: { prompt_tokens: 10, completion_tokens: 2, total_tokens: 12, cost: 0.0005 } });
    response.end("data: [DONE]\n\n");
  };
  const provider = createServer(async (req, res) => {
    let text = ""; for await (const part of req) text += part;
    const body = JSON.parse(text), followup = body.messages.some((m: { role: string }) => m.role === "tool");
    const pause = JSON.stringify(body.messages).includes("WAIT_FOR_CREDENTIAL_UPDATE") && !followup;
    const child = !body.tools?.some((tool: { function: { name: string } }) => tool.function.name === "interview") && body.messages.some((m: { role: string; content: unknown }) => m.role === "user" && JSON.stringify(m.content).includes("CHILD_TASK"));
    const delegate = body.messages.some((m: { role: string; content: unknown }) => m.role === "user" && JSON.stringify(m.content).includes("DELEGATE_CHILD"));
    const schedule = body.messages.some((m: { role: string; content: unknown }) => m.role === "user" && JSON.stringify(m.content).includes("CREATE_SCHEDULE"));
    const interview = body.messages.some((m: { role: string; content: unknown }) => m.role === "user" && JSON.stringify(m.content).includes("REQUEST_INTERVIEW"));
    const permission = body.messages.some((m: { role: string; content: unknown }) => m.role === "user" && JSON.stringify(m.content).includes("REQUEST_PERMISSION"));
    calls.push({ auth: String(req.headers.authorization), held: pause, followup, child, model: body.model, maxTokens: body.max_tokens ?? body.max_completion_tokens });
    res.writeHead(200, { "Content-Type": "text/event-stream" });
    chunk(res, { id: "begin", object: "chat.completion.chunk", choices: [{ index: 0, delta: { role: "assistant" }, finish_reason: null }] });
    if (pause) held = res;
    else if (child) heldChild = res;
    else if (delegate && !followup) finish(res, { name: "subagent", args: { agent: "scribe", task: "CHILD_TASK", context: "fresh", async: false } });
    else if (schedule && !followup) finish(res, { name: "subagent", args: { action: "schedule.create", id: "scheduled-qa", name: "Scheduled QA", every: "6h", workflow: "./scheduled-workflow.js" } });
    else if (interview && !followup) finish(res, { name: "interview", args: { title: "Local decision", questions: [{ id: "decision", type: "single", question: "Choose one", options: ["A", "B"] }] } });
    else if (permission && !followup) finish(res, { name: "bash", args: { command: "rm -r results-to-delete.txt" } });
    else finish(res);
  });
  await new Promise<void>(resolve => provider.listen(0, "127.0.0.1", resolve));
  const providerUrl = `http://127.0.0.1:${(provider.address() as { port: number }).port}/v1`;
  const fleet = new WorkerFleet(store, "http://127.0.0.1:0", "http://localhost:3000");
  fs.mkdirSync(path.dirname(fleet.tenantEnv(tenant.id)), { recursive: true });
  fs.writeFileSync(fleet.tenantEnv(tenant.id), "OPENROUTER_API_KEY=byok-old-env-key\n");
  const agentDir = path.join(root, "tenants", tenant.id, "pi-agent");
  fs.mkdirSync(agentDir, { recursive: true });
  fs.writeFileSync(path.join(agentDir, "models.json"), JSON.stringify({ providers: { openrouter: { baseUrl: providerUrl, api: "openai-completions" } } }));
  fs.writeFileSync(path.join(agentDir, "auth.json"), JSON.stringify({ openrouter: { type: "api_key", key: "byok-stored-old-key" } }));
  store.setSetting("openrouterKey", "platform-master-key");
  const gateway = new ModelGateway(store, undefined, `${providerUrl}/chat/completions`);
  const app = await buildManagementApp({ store, publicUrl: fleet.publicUrl, get managerUrl() { return fleet.managerUrl; }, fleet, gateway });
  fleet.managerUrl = await app.listen({ port: 0, host: "127.0.0.1" });
  const login = await store.login("researcher", "synthetic-admin-password");
  const browser = { cookie: `kady_session=${login.token}`, host: "localhost:3000", origin: "http://localhost:3000" };
  const api = async (projectId: string, route: string, method = "GET", body?: unknown) => fetch(`${fleet.managerUrl}/api${route}`, { method, headers: { ...browser, "X-Project-Id": projectId, ...(body ? { "Content-Type": "application/json" } : {}) }, ...(body ? { body: JSON.stringify(body) } : {}) });
  const session = async (pid: string) => (await (await api(pid, "/sessions", "POST")).json() as { id: string }).id;
  const run = (pid: string, sid: string, message: string) => api(pid, `/sessions/${sid}/run`, "POST", { message, model: "openrouter/openai/gpt-5.5", thinkingLevel: "off" });
  try {
    const platformSession = await session(p.id);
    const platformResult = await run(p.id, platformSession, "PLATFORM_TEST");
    const platformFrames = await platformResult.text();
    expect(platformFrames).toContain("Model answered.");
    expect(calls[0].auth).toBe("Bearer platform-master-key");
    expect(store.usage(tenant.id).spentUsd).toBe(0.0005);
    const largeOutput = await api(p.id, `/sessions/${await session(p.id)}/run`, "POST", { message: "LARGE_OUTPUT_LIMIT", model: "openrouter/~deepseek/deepseek-flash-latest", thinkingLevel: "off" });
    expect(await largeOutput.text()).toContain("Model answered.");
    expect(calls.at(-1)!.model).toBe("~deepseek/deepseek-flash-latest");
    expect(calls.at(-1)!.maxTokens).toBeGreaterThan(131072);
    const busySession = await session(a.id);
    await fleet.ensure(idle);
    const oldPid = fleet.live.get(a.id)!.child.pid;
    const busyResult = await run(a.id, busySession, "WAIT_FOR_CREDENTIAL_UPDATE");
    const busyFrames = busyResult.text();
    await vi.waitFor(() => expect(held).toBeDefined(), { timeout: 10000 });
    expect(calls.at(-1)!.auth).toBe("Bearer byok-stored-old-key");
    const switchBusy = await api(a.id, `/projects/${a.id}`, "PATCH", { supply: "platform" });
    expect(switchBusy.status).toBe(409);
    const changed = await api(a.id, "/credentials", "PUT", { openrouterApiKey: "byok-new-key" });
    expect(changed.status, await changed.clone().text()).toBe(200);
    expect(fleet.live.get(a.id)?.pending).toBe(true);
    expect(fleet.live.get(a.id)?.child.pid).toBe(oldPid);
    const denied = await run(a.id, busySession, "NEW_TASK_WHILE_PENDING");
    expect(denied.status).toBe(409);
    const idleSession = await session(idle.id);
    expect(await (await run(idle.id, idleSession, "NEW_IDLE_TASK")).text()).toContain("Model answered.");
    expect(calls.at(-1)!.auth).toBe("Bearer byok-new-key");
    finish(held!, true);
    expect(await busyFrames).toContain("Model answered.");
    expect(calls.find(c => c.followup)?.auth).toBe("Bearer byok-stored-old-key");
    await vi.waitFor(() => expect(fleet.live.get(a.id)?.pending).toBe(false), { timeout: 15000 });
    expect(fleet.live.get(a.id)?.child.pid).not.toBe(oldPid);
    expect((await api(a.id, `/sessions/${busySession}/history`)).status).toBe(200);
    expect(store.projects(user)).toHaveLength(3);
    const worker = await fleet.ensure(p);
    const agentFile = path.join(fleet.root(p), "projects", p.id, "sandbox", ".pi", "agents", "scribe.md");
    fs.mkdirSync(path.dirname(agentFile), { recursive: true });
    fs.writeFileSync(agentFile, "---\nname: scribe\ndescription: Local test assistant\nmodel: openrouter/openai/gpt-5.5\n---\nComplete the assigned task.\n");
    delegatedSession = await session(p.id);
    const delegated = await run(p.id, delegatedSession, "DELEGATE_CHILD");
    const delegatedFrames = delegated.text().then(text => { childTranscript = text; return text; });
    await vi.waitFor(() => expect(heldChild).toBeDefined(), { timeout: 15000 });
    expect(calls.find(c => c.child)?.auth).toBe("Bearer platform-master-key");
    const active = store.db.prepare("SELECT COUNT(*) n FROM task_leases WHERE projectId=?").get(p.id) as { n: number };
    expect(active.n).toBeGreaterThanOrEqual(1); // Kady detaches children; a finished parent releases its own slot.
    store.patchTenant(admin, tenant.id, { taskLimit: 1 });
    expect((await run(idle.id, await session(idle.id), "OVER_TASK_LIMIT")).status).toBe(429);
    expect((await api(idle.id, "/sandbox/latex-assist", "POST", {})).status).toBe(429);
    expect((await api(idle.id, `/sessions/${busySession}/notebook/example/next-experiments/generate`, "POST", {})).status).toBe(429);
    finish(heldChild!);
    expect(await delegatedFrames).toContain("Model answered.");
    await vi.waitFor(() => expect(store.db.prepare("SELECT COUNT(*) n FROM task_leases WHERE projectId=?").get(p.id)).toMatchObject({ n: 0 }), { timeout: 10000 });
    await vi.waitFor(async () => expect(await fleet.control(worker, "state")).toMatchObject({ busy: false }), { timeout: 15000 });
    store.patchTenant(admin, tenant.id, { taskLimit: 3 });
    const meter = (action: string, requestId: string) => fetch(`${worker.url}/subagents/meter/${action}`, { method: "POST", headers: { "X-Kady-Token": worker.auth, "X-Project-Id": p.id, "Content-Type": "application/json" }, body: JSON.stringify({ projectId: p.id, sessionId: delegatedSession, childSessionId: "same-child", provider: "openrouter", model: "openai/gpt-5.5", kind: "watchdog", authType: "api_key", requestId, ...(action === "usage" ? { usage: { input: 0, output: 0, cost: { total: 0 } } } : {}) }) });
    expect((await meter("admit", "review-one")).status).toBe(200);
    expect((await meter("admit", "review-two")).status).toBe(200);
    expect(store.db.prepare("SELECT COUNT(*) n FROM task_leases WHERE projectId=?").get(p.id)).toMatchObject({ n: 2 });
    await meter("usage", "review-one"); await meter("usage", "review-two");
    expect(store.db.prepare("SELECT COUNT(*) n FROM task_leases WHERE projectId=?").get(p.id)).toMatchObject({ n: 0 });
    fs.writeFileSync(path.join(fleet.root(p), "projects", p.id, "sandbox", "scheduled-workflow.js"), 'return runs.run("main", { agent: "scribe", task: "SCHEDULED_TASK", model: "openrouter/openai/gpt-5.5" })');
    const createdSchedule = await run(p.id, await session(p.id), "CREATE_SCHEDULE");
    scheduleTranscript = await createdSchedule.text();
    expect(scheduleTranscript).toContain("scheduled-qa");
    const schedules = await (await api(p.id, "/schedules")).json() as { schedules: { id: string; paused: boolean }[] };
    expect(schedules.schedules).toContainEqual(expect.objectContaining({ id: "scheduled-qa", paused: false }));
    expect((await api(p.id, `/projects/${p.id}`, "PATCH", { supply: "byok" })).status).toBe(409);
    store.patchTenant(admin, tenant.id, { budgetUsd: 0 });
    expect((await api(p.id, "/schedules/scheduled-qa/run", "POST", {})).status).toBe(402);
    store.patchTenant(admin, tenant.id, { budgetUsd: null });
    const before = calls.length;
    expect((await api(p.id, "/schedules/scheduled-qa/run", "POST", {})).status).toBe(200);
    await vi.waitFor(() => expect(calls.length).toBeGreaterThan(before), { timeout: 15000 });
    expect(calls.slice(before).every(call => call.auth === "Bearer platform-master-key")).toBe(true);
    expect((await api(p.id, "/schedules/scheduled-qa/pause", "POST", {})).status).toBe(200);
    await vi.waitFor(async () => expect(await fleet.control(worker, "state")).toMatchObject({ busy: false, scheduled: false }), { timeout: 15000 });
    const interviewSession = await session(p.id), interviewResult = await run(p.id, interviewSession, "REQUEST_INTERVIEW"), interviewFrames = interviewResult.text();
    await vi.waitFor(async () => {
      const state = await (await api(p.id, `/sessions/${interviewSession}/run/state`)).json();
      expect(JSON.stringify(state)).toContain("Local decision");
    }, { timeout: 10000 });
    expect((await api(p.id, `/sessions/${interviewSession}/interview/scan`, "POST", { responses: [{ id: "decision", value: "A" }] })).status).toBe(200);
    expect(await interviewFrames).toContain("Model answered.");
    const artifact = path.join(fleet.root(p), "projects", p.id, "sandbox", "results-to-delete.txt"); fs.writeFileSync(artifact, "keep this");
    const permissionSession = await session(p.id), permissionResult = await run(p.id, permissionSession, "REQUEST_PERMISSION"), permissionFrames = permissionResult.text();
    let requestId = "";
    await vi.waitFor(async () => {
      const state = await (await api(p.id, `/sessions/${permissionSession}/run/state`)).json();
      controlState = JSON.stringify(state);
      requestId = state.run.frames.find((frame: { type: string }) => frame.type === "permission_request")?.requestId;
      expect(requestId).toBeTruthy();
    }, { timeout: 10000 });
    expect((await api(p.id, `/sessions/${permissionSession}/permissions/${requestId}`, "POST", { allow: false })).status).toBe(200);
    expect(await permissionFrames).toContain("Model answered.");
    expect(fs.readFileSync(artifact, "utf8")).toBe("keep this");
  } catch (error) {
    const file = path.join(fleet.root(p), "worker.log");
    const status = delegatedSession ? await (await api(p.id, `/sessions/${delegatedSession}/subagents`)).text().catch(() => "status unavailable") : "";
    let childDetail = "";
    try { const runId = JSON.parse(status).asyncSnapshot.runs[0].id; childDetail = await (await api(p.id, `/sessions/${delegatedSession}/subagents/transcript`, "POST", { runId })).text(); } catch {}
    throw new Error(`${(error as Error).message}\n${controlState.slice(-12000)}\n${scheduleTranscript.slice(-12000)}\n${childDetail.slice(-14000)}\n${status.slice(-10000)}\n${childTranscript.slice(-14000)}\n${fs.existsSync(file) ? fs.readFileSync(file, "utf8").slice(-8000) : "No worker log"}`);
  } finally { held?.destroy(); heldChild?.destroy(); await app.close(); provider.closeAllConnections(); await new Promise<void>(resolve => provider.close(() => resolve())); store.close(); fs.rmSync(root, { recursive: true, force: true }); }
}, 90000);
